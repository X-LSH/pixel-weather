const GLYPH_W = 5;
const GLYPH_H = 7;

export function measureText(text, scale = 1, tracking = 1) {
  const n = text.length;
  if (n === 0) return 0;
  return n * GLYPH_W * scale + (n - 1) * tracking * scale;
}

export function drawText(ctx, x, y, text, color, scale = 1, tracking = 1) {
  let cx = x;
  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const g = GLYPHS[text[i].toUpperCase()] || GLYPHS[' '];
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = g[r];
      if (!bits) continue;
      let run = -1;
      for (let b = 0; b <= GLYPH_W; b++) {
        const on = b < GLYPH_W && (bits & (1 << (GLYPH_W - 1 - b)));
        if (on && run < 0) run = b;
        if (!on && run >= 0) {
          ctx.fillRect(cx + run * scale, y + r * scale, (b - run) * scale, scale);
          run = -1;
        }
      }
    }
    cx += (GLYPH_W + tracking) * scale;
  }
  return cx - x;
}

/** 角落信息条：单行极简，深色底板保证任何天气下都可读，又不抢画面主体 */
export function drawHud(ctx, env) {
  const { m, hud } = env;
  const scale = 1;
  const pad = 3;
  const tempText = `${Math.round(hud.temp)}\u00b0C`;
  const maxChars = Math.max(6, Math.floor((m.W - 18) / (GLYPH_W + 1)));

  let line = `${hud.city} ${tempText} ${hud.label}`;
  if (line.length > maxChars) line = `${hud.city} ${tempText}`;
  if (line.length > maxChars) line = hud.city.slice(0, maxChars);

  const w = measureText(line, scale) + pad * 2;
  const h = GLYPH_H * scale + pad * 2;
  const x = 5;
  const y = m.H - h - 5;

  ctx.fillStyle = rgbaStr([10, 13, 24], 0.32);
  ctx.fillRect(x, y, w, h);
  drawText(ctx, x + pad, y + pad, line, rgbStr([228, 236, 248]), scale);
}
